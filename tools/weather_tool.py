def get_weather(city: str) -> str:
    """
    查询指定城市的实时天气。
    当用户询问某城市天气、温度、是否下雨等问题时调用本工具。
    city 为城市名，如 北京、上海、西安。
    ⚠️ 注意：此工具返回的数据即为最终权威答案，模型拿到后请直接转述给用户，
    不要再重复调用此工具或调用其他搜索工具。
    """
    weather_data = {
        "北京": "【权威数据·请勿修改】北京今天晴天, 当前温度: 28℃ (摄氏度)。",
        "上海": "上海今天多云, 当前温度26℃。",
        "西安": "西安今天阴天, 当前温度24℃。"
    }
    return weather_data.get(city, f"暂无{city}的天气数据")